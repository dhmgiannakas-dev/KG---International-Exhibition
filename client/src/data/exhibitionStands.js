/**
 * Find a stand by its unique URL ID.
 */
export function getExhibitionStand(id) {
  return exhibitionStands.find((stand) => stand.id === id);
}

/**
 * Safe fallback for missing project details.
 */
export function getStandDetail(value) {
  if (value === null || value === undefined) {
    return "Information not available";
  }

  if (typeof value === "string" && value.trim() === "") {
    return "Information not available";
  }

  return value;
}

/**
 * Return unique, non-empty gallery images.
 * Fall back to the main image if images is empty.
 */
export function getStandImages(stand) {
  if (!stand) {
    return [];
  }

  const images = Array.isArray(stand.images)
    ? stand.images.filter(
        (url) =>
          typeof url === "string" &&
          url.trim() !== ""
      )
    : [];

  if (images.length > 0) {
    return [...new Set(images)];
  }

  return typeof stand.image === "string" &&
    stand.image.trim() !== ""
    ? [stand.image]
    : [];
}
